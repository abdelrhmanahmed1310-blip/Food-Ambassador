import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createProduct, listUnits } from "@/modules/catalog/service";
import { postOpeningBalance } from "@/modules/inventory/operations";
import { businessDate } from "@/modules/inventory/rules";
import { addMenuItemPrice, createMenuCategory, createMenuItem } from "@/modules/menu/service";
import {
  createRegister,
  getOrder,
  openShift,
  refundOrder,
  submitOrder,
} from "@/modules/pos/service";
import { createBranch } from "@/modules/sites/branches";
import { createWarehouse } from "@/modules/sites/warehouses";
import type { TenantContext } from "@/modules/tenancy/context";
import { getDb } from "@/server/db/client";
import { addMember, createTenant } from "../../../test/support/factories";
import { DASHBOARD_DAYS, salesDashboard } from "./service";

/** Overview dashboard (ADR-078): real POS figures only, scoped like the reports. */

let ctx: TenantContext;
let other: TenantContext;
let cashier: TenantContext;
let analyst: TenantContext;
let register: string;
let shiftId: string;
const items: Record<string, string> = {};
const TZ = "Asia/Riyadh";

/** Sells at the till and returns the order id (generated by the device, as the till does). */
async function sell(lines: Array<[string, number]>, total: string) {
  const orderId = randomUUID();
  await submitOrder(ctx, {
    orderId,
    registerId: register,
    shiftId,
    channel: "TAKEAWAY",
    lines: lines.map(([code, qty]) => ({ itemId: items[code], quantity: String(qty) })),
    payments: [{ method: "CARD", amount: total }],
  });
  return orderId;
}

beforeAll(async () => {
  ({ ctx } = await createTenant("dash", { baseCurrency: "EGP", timeZone: TZ }));
  ({ ctx: other } = await createTenant("dash-other", { baseCurrency: "EGP", timeZone: TZ }));
  ({ ctx: cashier } = await addMember(ctx, "cashier"));
  ({ ctx: analyst } = await addMember(ctx, "analyst"));
  const each = (await listUnits(ctx)).find((u) => u.code === "each")!.id;
  const branchId = (await createBranch(ctx, { code: "B1", name: "Branch", type: "RESTAURANT" })).id;
  const warehouseId = (
    await createWarehouse(ctx, { branchId, code: "K1", name: "Kitchen", type: "KITCHEN_STORE" })
  ).id;
  const category = (await createMenuCategory(ctx, { name: "Menu" })).id;
  for (const [code, price, cost] of [
    ["BURGER", "50", "20"],
    ["COLA", "10", "3"],
  ]) {
    const productId = (
      await createProduct(ctx, { sku: code, nameEn: code, type: "FINISHED_GOOD", baseUomId: each })
    ).id;
    await postOpeningBalance(ctx, {
      warehouseId,
      productId,
      quantity: "100",
      uomId: each,
      unitCost: cost,
    });
    items[code] = (
      await createMenuItem(ctx, { code, name: code, categoryId: category, kind: "ITEM", productId })
    ).id;
    await addMenuItemPrice(ctx, items[code], {
      channel: "TAKEAWAY",
      price,
      effectiveFrom: businessDate(TZ),
    });
  }
  register = (await createRegister(ctx, { branchId, warehouseId, code: "T1", name: "Till" })).id;
  shiftId = (await openShift(ctx, register, { openingFloat: "0" })).id;
});

afterAll(async () => {
  await getDb().$disconnect();
});

describe("overview sales dashboard (ADR-078)", () => {
  it("shows nothing invented before any sale: 14 zero days, no average ticket", async () => {
    const d = (await salesDashboard(ctx))!;
    expect(d.series).toHaveLength(DASHBOARD_DAYS);
    expect(d.series.every((x) => x.orders === 0 && x.net.isZero())).toBe(true);
    expect(d.today.averageTicket).toBeNull();
    expect(d.top).toEqual([]);
    expect(d.series.at(-1)!.day).toBe(businessDate(TZ));
  });

  it("adds up today's paid orders, refunds deducted, best sellers by net", async () => {
    await sell(
      [
        ["BURGER", 2],
        ["COLA", 1],
      ],
      "110",
    );
    const second = await sell([["COLA", 3]], "30");
    // Refund one cola of the second order (no VAT set up: net = amount).
    const order = await getOrder(ctx, second);
    await refundOrder(ctx, second, {
      registerId: register,
      method: "CARD",
      reason: "Spilt",
      lines: [{ orderLineId: order.lines[0].id, quantity: "1" }],
    });
    const d = (await salesDashboard(ctx))!;
    expect(d.today.orders).toBe(2);
    expect(d.today.net.toFixed(2)).toBe("130.00");
    expect(d.today.averageTicket!.toFixed(2)).toBe("65.00");
    expect(d.period.net.toFixed(2)).toBe("130.00");
    expect(d.top.map((t) => [t.name, t.quantity.toFixed(0)])).toEqual([
      ["BURGER", "2"],
      ["COLA", "3"],
    ]);
    // The owner may see costs: stock used 2×20 + 4×3 = 52 against net 130.
    expect(d.costs!.foodCost!.toFixed(4)).toBe("0.4000");
  });

  it("is scoped: no sales access means no dashboard", async () => {
    expect(await salesDashboard(cashier)).toBeNull();
    // The read-only analyst sees sales and stock value, so sales and costs.
    const a = (await salesDashboard(analyst))!;
    expect(a.today.orders).toBe(2);
    expect(a.costs).not.toBeNull();
  });

  it("never mixes organizations", async () => {
    const d = (await salesDashboard(other))!;
    expect(d.period.orders).toBe(0);
    expect(d.top).toEqual([]);
  });
});
